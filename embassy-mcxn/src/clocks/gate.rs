//! Clock gate trait and free functions for enabling/disabling peripheral
//! clocks through SYSCON.
//!
//! MCXN947 gates AHB peripheral clocks through `SYSCON0.AHBCLKCTRLn` and resets
//! them through `SYSCON0.PRESETCTRLn` (RM "Chapter 17 System Controller
//! (SYSCON)"). A peripheral's clock-enable and reset bits share the same bit
//! position within their respective register index.
//!
//! Gates are driven through the write-1-to-act `AHBCLKCTRLSET`/`CLR` and
//! `PRESETCTRLSET`/`CLR` aliases rather than by read-modify-write on the plain
//! registers. That makes each operation atomic, so two concurrent `enable`
//! calls cannot lose one another's bit, and it cannot disturb reset-set bits
//! that the PAC fieldsets do not model (`AHBCLKCTRL0` resets to `0x603`,
//! `PRESETCTRL0` to `0x100`).

use crate::pac::common::{Access, Reg};

/// A zeroed value of the fieldset type behind `_reg`.
///
/// Lets `impl_syscon_gate!` name a peripheral's bit through the PAC's field
/// setter without naming the fieldset type, which the PAC does not export
/// under a stable name.
#[inline(always)]
fn zeroed_fieldset<T: Copy + Default, A: Access>(_reg: &Reg<T, A>) -> T {
    T::default()
}

/// Trait describing an AHB clock gate that can be toggled through SYSCON.
///
/// Implementors supply the register index and the two bit masks; every other
/// method is provided. Implementations are generated by `impl_syscon_gate!`.
pub trait Gate {
    /// Index of this peripheral's `AHBCLKCTRLn`/`PRESETCTRLn` register pair.
    const REG_IDX: usize;

    /// This peripheral's clock-enable bit within `AHBCLKCTRL[REG_IDX]`.
    fn clk_mask() -> u32;

    /// This peripheral's reset bit within `PRESETCTRL[REG_IDX]`.
    fn rst_mask() -> u32;

    /// Enable the clock gate.
    ///
    /// # Safety
    ///
    /// The current peripheral must be disabled prior to calling this method.
    #[inline]
    unsafe fn enable_clock() {
        crate::pac::SYSCON0
            .ahbclkctrlset(Self::REG_IDX)
            .write(|w| w.set_data(Self::clk_mask()));
    }

    /// Disable the clock gate.
    ///
    /// # Safety
    ///
    /// There must be no active user of this peripheral when calling this method.
    #[inline]
    unsafe fn disable_clock() {
        crate::pac::SYSCON0
            .ahbclkctrlclr(Self::REG_IDX)
            .write(|w| w.set_data(Self::clk_mask()));
    }

    /// Drive the peripheral into reset.
    ///
    /// # Safety
    ///
    /// There must be no active user of this peripheral when calling this method.
    #[inline]
    unsafe fn assert_reset() {
        crate::pac::SYSCON0
            .presetctrlset(Self::REG_IDX)
            .write(|w| w.set_data(Self::rst_mask()));
    }

    /// Drive the peripheral out of reset.
    ///
    /// # Safety
    ///
    /// There must be no active user of this peripheral when calling this method.
    #[inline]
    unsafe fn release_reset() {
        crate::pac::SYSCON0
            .presetctrlclr(Self::REG_IDX)
            .write(|w| w.set_data(Self::rst_mask()));
    }

    /// Return whether the clock gate for this peripheral is currently enabled.
    #[inline]
    fn is_clock_enabled() -> bool {
        ahbclkctrl_bits(Self::REG_IDX) & Self::clk_mask() != 0
    }

    /// Return whether the peripheral is currently out of reset.
    #[inline]
    fn is_reset_released() -> bool {
        presetctrl_bits(Self::REG_IDX) & Self::rst_mask() == 0
    }
}

/// `AHBCLKCTRL0..3` are four separately-named registers rather than an array,
/// so reading one by index needs a match. Only the SET/CLR aliases are
/// modelled as arrays.
#[inline]
fn ahbclkctrl_bits(idx: usize) -> u32 {
    let s = crate::pac::SYSCON0;
    match idx {
        0 => s.ahbclkctrl0().read().0,
        1 => s.ahbclkctrl1().read().0,
        2 => s.ahbclkctrl2().read().0,
        _ => s.ahbclkctrl3().read().0,
    }
}

/// As [`ahbclkctrl_bits`], for the reset registers.
#[inline]
fn presetctrl_bits(idx: usize) -> u32 {
    let s = crate::pac::SYSCON0;
    match idx {
        0 => s.presetctrl0().read().0,
        1 => s.presetctrl1().read().0,
        2 => s.presetctrl2().read().0,
        _ => s.presetctrl3().read().0,
    }
}

/// Enable the clock gate for the given peripheral, then pulse its reset line.
///
/// # Safety
///
/// This peripheral must not yet be in use prior to calling `enable_and_reset`.
#[inline]
pub unsafe fn enable_and_reset<G: Gate>() {
    unsafe {
        enable::<G>();
        pulse_reset::<G>();
    }
}

/// Enable the clock gate for the given peripheral.
///
/// Prefer [`enable_and_reset`] unless you are specifically avoiding a pulse
/// of the reset, or need to control the duration of the pulse more directly.
///
/// # Safety
///
/// This peripheral must not yet be in use prior to calling `enable`.
#[inline]
pub unsafe fn enable<G: Gate>() {
    unsafe {
        G::enable_clock();
        while !G::is_clock_enabled() {}
        core::arch::asm!("dsb sy; isb sy", options(nomem, nostack, preserves_flags));
    }
}

/// Disable the clock gate for the given peripheral.
///
/// # Safety
///
/// This peripheral must no longer be in use prior to calling `disable`.
#[inline]
pub unsafe fn disable<G: Gate>() {
    unsafe {
        G::disable_clock();
    }
}

/// Check whether a gate is currently enabled.
#[inline]
pub fn is_clock_enabled<G: Gate>() -> bool {
    G::is_clock_enabled()
}

/// Release the reset line for the given peripheral.
///
/// Prefer [`enable_and_reset`].
///
/// # Safety
///
/// This peripheral must not yet be in use prior to calling `release_reset`.
#[inline]
pub unsafe fn release_reset<G: Gate>() {
    unsafe {
        G::release_reset();
    }
}

/// Assert the reset line for the given peripheral.
///
/// Prefer [`enable_and_reset`].
///
/// # Safety
///
/// This peripheral must no longer be in use prior to calling `assert_reset`.
#[inline]
pub unsafe fn assert_reset<G: Gate>() {
    unsafe {
        G::assert_reset();
    }
}

/// Check whether a peripheral is currently out of reset.
#[inline]
pub fn is_reset_released<G: Gate>() -> bool {
    G::is_reset_released()
}

/// Pulse the reset line for the given peripheral.
///
/// Prefer [`enable_and_reset`].
///
/// # Safety
///
/// This peripheral must not yet be in use prior to calling `pulse_reset`.
#[inline]
pub unsafe fn pulse_reset<G: Gate>() {
    unsafe {
        G::assert_reset();
        cortex_m::asm::nop();
        cortex_m::asm::nop();
        G::release_reset();
        while !G::is_reset_released() {}
    }
}

/// Implements [`Gate`] for a peripheral gated through `SYSCON0.AHBCLKCTRL{idx}`
/// and reset through `SYSCON0.PRESETCTRL{idx}`.
///
/// `clk:` and `rst:` name the plain register and the PAC field setter for the
/// peripheral's bit in it. The mask is derived by calling that setter on a
/// zeroed fieldset, so the bit position always comes from the PAC.
macro_rules! impl_syscon_gate {
    ($name:ident, $idx:expr, clk: $clk_reg:ident . $clk_set:ident, rst: $rst_reg:ident . $rst_set:ident) => {
        impl crate::clocks::Gate for crate::peripherals::$name {
            const REG_IDX: usize = $idx;

            #[inline(always)]
            fn clk_mask() -> u32 {
                let mut r = zeroed_fieldset(&crate::pac::SYSCON0.$clk_reg());
                r.$clk_set(1u8.into());
                r.0
            }

            #[inline(always)]
            fn rst_mask() -> u32 {
                let mut r = zeroed_fieldset(&crate::pac::SYSCON0.$rst_reg());
                r.$rst_set(1u8.into());
                r.0
            }
        }
    };
}

// PORT0-4 / GPIO0-4: gated via SYSCON0.AHBCLKCTRL0 / PRESETCTRL0 (RM Chapter
// 17). GPIO5/PORT5 live in the always-on VBAT domain and are always clocked
// (RM "Chapter 33 Clocking", Table 319, `slow_clk`), with no AHB clock gate or
// reset bit.
impl_syscon_gate!(PORT0, 0, clk: ahbclkctrl0.set_port0, rst: presetctrl0.set_port0_rst);
impl_syscon_gate!(PORT1, 0, clk: ahbclkctrl0.set_port1, rst: presetctrl0.set_port1_rst);
impl_syscon_gate!(PORT2, 0, clk: ahbclkctrl0.set_port2, rst: presetctrl0.set_port2_rst);
impl_syscon_gate!(PORT3, 0, clk: ahbclkctrl0.set_port3, rst: presetctrl0.set_port3_rst);
impl_syscon_gate!(PORT4, 0, clk: ahbclkctrl0.set_port4, rst: presetctrl0.set_port4_rst);
impl_syscon_gate!(GPIO0, 0, clk: ahbclkctrl0.set_gpio0, rst: presetctrl0.set_gpio0_rst);
impl_syscon_gate!(GPIO1, 0, clk: ahbclkctrl0.set_gpio1, rst: presetctrl0.set_gpio1_rst);
impl_syscon_gate!(GPIO2, 0, clk: ahbclkctrl0.set_gpio2, rst: presetctrl0.set_gpio2_rst);
impl_syscon_gate!(GPIO3, 0, clk: ahbclkctrl0.set_gpio3, rst: presetctrl0.set_gpio3_rst);
impl_syscon_gate!(GPIO4, 0, clk: ahbclkctrl0.set_gpio4, rst: presetctrl0.set_gpio4_rst);
