//! GPIO driver.
//!
//! A pin is a pad in one of the PORT blocks (`PORT0`-`PORT5`), which selects
//! the pad's function and electrical settings through its `PCRn` register,
//! and a bit in the matching GPIO block (`GPIO0`-`GPIO5`), which holds the
//! data and direction registers.
//!
//! Each PORT bank has its own generated PAC type, with a distinct type per
//! `PCRn` register, so pad settings are written through the raw `PCRn` word
//! at its documented offset rather than through typed field accessors. The
//! GPIO data and direction registers are shared across banks and use the
//! PAC's typed accessors.
//!
//! The driver is blocking only: there is no interrupt-driven `wait_for_*`.

use core::convert::Infallible;

use embassy_hal_internal::{Peri, PeripheralType};

use crate::pac::common::{RW, Reg};
use crate::pac::gpio::{Gpio, Pdd, Pid, Ptco, Ptso};

/// Digital input or output level.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[cfg_attr(feature = "defmt", derive(defmt::Format))]
pub enum Level {
    /// Logical low.
    Low,
    /// Logical high.
    High,
}

impl From<bool> for Level {
    fn from(val: bool) -> Self {
        match val {
            true => Self::High,
            false => Self::Low,
        }
    }
}

impl From<Level> for bool {
    fn from(level: Level) -> bool {
        match level {
            Level::Low => false,
            Level::High => true,
        }
    }
}

/// Pull setting for an input.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[cfg_attr(feature = "defmt", derive(defmt::Format))]
pub enum Pull {
    /// No pull resistor.
    None,
    /// Internal pull-up resistor.
    Up,
    /// Internal pull-down resistor.
    Down,
}

/// Output slew rate.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[cfg_attr(feature = "defmt", derive(defmt::Format))]
pub enum SlewRate {
    /// Fast slew rate.
    Fast,
    /// Slow slew rate.
    Slow,
}

/// Output drive strength.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[cfg_attr(feature = "defmt", derive(defmt::Format))]
pub enum DriveStrength {
    /// Normal drive strength.
    Normal,
    /// Double drive strength.
    Double,
}

/// Input logic inversion.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[cfg_attr(feature = "defmt", derive(defmt::Format))]
pub enum Inverter {
    /// The input is read as driven.
    Disabled,
    /// The input is read inverted.
    Enabled,
}

/// Offset of `PCR0` within every PORT bank; `PCRn` follows at 4-byte strides.
const PCR_OFFSET: usize = 0x80;

// `PCRn` field positions (RM, PORT chapter, "Pin Control"). Each is one bit
// wide except `MUX`, which is four.
const PCR_PS: u32 = 0;
const PCR_PE: u32 = 1;
const PCR_SRE: u32 = 3;
const PCR_ODE: u32 = 5;
const PCR_DSE: u32 = 6;
const PCR_MUX: u32 = 8;
const PCR_MUX_MASK: u32 = 0xf;
const PCR_IBE: u32 = 12;
const PCR_INV: u32 = 13;

#[inline(always)]
fn pcr_field(reg: &mut u32, shift: u32, mask: u32, val: u32) {
    *reg = (*reg & !(mask << shift)) | ((val & mask) << shift);
}

#[inline(always)]
fn pcr_bit(reg: &mut u32, shift: u32, set: bool) {
    pcr_field(reg, shift, 1, set as u32);
}

/// Pad and data-register access for a pin.
///
/// Only `port` and `pin` are per-pin; everything else is derived from them,
/// so the impls generated by `impl_gpio_pin!` and the one for [`AnyPin`] carry
/// no register code of their own.
pub(crate) trait SealedPin {
    /// The PORT/GPIO bank (0-5) this pin belongs to.
    fn port(&self) -> u8;

    /// The bit position (0-31) of this pin within its bank.
    fn pin(&self) -> u8;

    /// The GPIO data-register block for this pin's bank.
    #[inline(always)]
    fn gpio(&self) -> Gpio {
        match self.port() {
            0 => crate::pac::GPIO0,
            1 => crate::pac::GPIO1,
            2 => crate::pac::GPIO2,
            3 => crate::pac::GPIO3,
            4 => crate::pac::GPIO4,
            _ => crate::pac::GPIO5,
        }
    }

    /// This pin's pad control register (`PCRn`).
    #[inline(always)]
    fn pcr_reg(&self) -> Reg<u32, RW> {
        let base = match self.port() {
            0 => crate::pac::PORT0.as_ptr(),
            1 => crate::pac::PORT1.as_ptr(),
            2 => crate::pac::PORT2.as_ptr(),
            3 => crate::pac::PORT3.as_ptr(),
            4 => crate::pac::PORT4.as_ptr(),
            _ => crate::pac::PORT5.as_ptr(),
        };
        let addr = (base as *mut u8).wrapping_add(PCR_OFFSET + 4 * self.pin() as usize);
        // SAFETY: every PORT bank has `PCR0`-`PCR31` at this offset, and `pin`
        // is in 0..32 for every pin this crate constructs.
        unsafe { Reg::from_ptr(addr as *mut u32) }
    }

    /// Route the pad to GPIO, which is function 0 on every pin of this chip.
    #[inline(always)]
    fn set_function_gpio(&self) {
        self.pcr_reg().modify(|w| pcr_field(w, PCR_MUX, PCR_MUX_MASK, 0));
    }

    #[inline(always)]
    fn set_pull(&self, pull: Pull) {
        let (enable, up) = match pull {
            Pull::None => (false, false),
            Pull::Up => (true, true),
            Pull::Down => (true, false),
        };
        self.pcr_reg().modify(|w| {
            pcr_bit(w, PCR_PE, enable);
            pcr_bit(w, PCR_PS, up);
        });
    }

    #[inline(always)]
    fn set_drive_strength(&self, strength: DriveStrength) {
        self.pcr_reg()
            .modify(|w| pcr_bit(w, PCR_DSE, strength == DriveStrength::Double));
    }

    #[inline(always)]
    fn set_slew_rate(&self, slew_rate: SlewRate) {
        self.pcr_reg()
            .modify(|w| pcr_bit(w, PCR_SRE, slew_rate == SlewRate::Slow));
    }

    #[inline(always)]
    fn set_enable_input_buffer(&self, enabled: bool) {
        self.pcr_reg().modify(|w| pcr_bit(w, PCR_IBE, enabled));
    }

    #[inline(always)]
    fn set_open_drain(&self, open_drain: bool) {
        self.pcr_reg().modify(|w| pcr_bit(w, PCR_ODE, open_drain));
    }

    #[inline(always)]
    fn set_input_inversion(&self, invert: Inverter) {
        self.pcr_reg()
            .modify(|w| pcr_bit(w, PCR_INV, invert == Inverter::Enabled));
    }

    /// Return the pin to its reset state: GPIO function, direction input, input
    /// buffer off, and disabled for general-purpose input.
    #[inline(always)]
    fn set_as_disconnected(&self) {
        let n = self.pin() as usize;
        self.gpio().pddr().modify(|w| w.set_pdd(n, Pdd::Pdd0));
        self.set_enable_input_buffer(false);
        self.set_function_gpio();
        self.gpio().pidr().modify(|w| w.set_pid(n, Pid::Pid1));
    }
}

/// Interface for a peripheral that is a GPIO pin.
#[allow(private_bounds)]
pub trait Pin: PeripheralType + Into<AnyPin> + SealedPin + Sized + 'static {
    /// Number of the pin within its bank.
    #[inline]
    fn pin_index(&self) -> u8 {
        self.pin()
    }

    /// The PORT/GPIO bank of the pin.
    #[inline]
    fn port_index(&self) -> u8 {
        self.port()
    }
}

/// Type-erased GPIO pin.
pub struct AnyPin {
    port: u8,
    pin: u8,
}

impl AnyPin {
    /// An `AnyPin` for a bank and pin number, for the `From` impls generated
    /// by `impl_gpio_pin!`.
    #[inline(always)]
    pub(crate) const fn new(port: u8, pin: u8) -> Self {
        Self { port, pin }
    }

    /// Unsafely create an `AnyPin` from a bank and pin number.
    ///
    /// # Safety
    ///
    /// `port` must be 0-5 and `pin` 0-31 and name a pin present on the chip,
    /// and you must ensure that you're only using one instance of this type
    /// for that pin at a time.
    #[inline]
    pub unsafe fn steal(port: u8, pin: u8) -> Peri<'static, Self> {
        // SAFETY: the caller upholds uniqueness and validity.
        unsafe { Peri::new_unchecked(Self::new(port, pin)) }
    }
}

embassy_hal_internal::impl_peripheral!(AnyPin);

impl SealedPin for AnyPin {
    #[inline(always)]
    fn port(&self) -> u8 {
        self.port
    }

    #[inline(always)]
    fn pin(&self) -> u8 {
        self.pin
    }
}

impl Pin for AnyPin {}

#[doc(hidden)]
#[macro_export]
macro_rules! impl_gpio_pin {
    ($peri:ident, $port:expr, $pin:expr) => {
        impl $crate::gpio::SealedPin for $crate::peripherals::$peri {
            #[inline(always)]
            fn port(&self) -> u8 {
                $port
            }

            #[inline(always)]
            fn pin(&self) -> u8 {
                $pin
            }
        }

        impl $crate::gpio::Pin for $crate::peripherals::$peri {}

        impl From<$crate::peripherals::$peri> for $crate::gpio::AnyPin {
            #[inline]
            fn from(_val: $crate::peripherals::$peri) -> Self {
                $crate::gpio::AnyPin::new($port, $pin)
            }
        }
    };
}

/// GPIO flexible pin driver.
///
/// A pin whose direction can be changed at runtime. [`Input`], [`Output`] and
/// [`OutputOpenDrain`] are thin wrappers around it.
pub struct Flex<'d> {
    pin: Peri<'d, AnyPin>,
}

impl<'d> Flex<'d> {
    /// Wrap the pin in a `Flex`.
    ///
    /// The pin is routed to GPIO and left disconnected until configured. The
    /// output level is unspecified, but can be set before the pin is put into
    /// output mode.
    #[inline]
    pub fn new(pin: Peri<'d, impl Pin>) -> Self {
        let pin = pin.into();
        pin.set_as_disconnected();
        Self { pin }
    }

    #[inline(always)]
    fn n(&self) -> usize {
        self.pin.pin() as usize
    }

    /// Number of the pin within its bank.
    #[inline]
    pub fn pin_index(&self) -> u8 {
        self.pin.pin()
    }

    /// The PORT/GPIO bank of the pin.
    #[inline]
    pub fn port_index(&self) -> u8 {
        self.pin.port()
    }

    /// Put the pin into input mode.
    ///
    /// The pull setting is left as it was; see [`Flex::set_pull`].
    #[inline]
    pub fn set_as_input(&mut self) {
        let n = self.n();
        self.pin.set_enable_input_buffer(true);
        self.pin.gpio().pidr().modify(|w| w.set_pid(n, Pid::Pid0));
        self.pin.gpio().pddr().modify(|w| w.set_pdd(n, Pdd::Pdd0));
    }

    /// Put the pin into output mode.
    ///
    /// The pull resistor is disabled. Whether the output is push-pull or
    /// open-drain is set by [`Flex::set_open_drain`].
    #[inline]
    pub fn set_as_output(&mut self) {
        let n = self.n();
        self.pin.set_pull(Pull::None);
        self.pin.gpio().pidr().modify(|w| w.set_pid(n, Pid::Pid0));
        self.pin.gpio().pddr().modify(|w| w.set_pdd(n, Pdd::Pdd1));
    }

    /// Put the pin into disconnected mode: input direction, input buffer off,
    /// and disabled for general-purpose input.
    #[inline]
    pub fn set_as_disconnected(&mut self) {
        self.pin.set_as_disconnected();
    }

    /// Is the pin configured as an output?
    #[inline]
    pub fn is_output(&self) -> bool {
        self.pin.gpio().pddr().read().pdd(self.n()) == Pdd::Pdd1
    }

    /// Is the pin configured as an input?
    #[inline]
    pub fn is_input(&self) -> bool {
        !self.is_output() && self.pin.gpio().pidr().read().pid(self.n()) == Pid::Pid0
    }

    /// Is the pin disconnected?
    #[inline]
    pub fn is_disconnected(&self) -> bool {
        !self.is_output() && !self.is_input()
    }

    /// Set the output as high.
    #[inline]
    pub fn set_high(&mut self) {
        let n = self.n();
        self.pin.gpio().psor().write(|w| w.set_ptso(n, Ptso::Ptso1));
    }

    /// Set the output as low.
    #[inline]
    pub fn set_low(&mut self) {
        let n = self.n();
        self.pin.gpio().pcor().write(|w| w.set_ptco(n, Ptco::Ptco1));
    }

    /// Set the output level.
    #[inline]
    pub fn set_level(&mut self, level: Level) {
        match level {
            Level::High => self.set_high(),
            Level::Low => self.set_low(),
        }
    }

    /// Toggle the output level.
    #[inline]
    pub fn toggle(&mut self) {
        let n = self.n();
        self.pin.gpio().ptor().write(|w| w.set_ptto(n, true));
    }

    /// Get whether the pin input level is high.
    #[inline]
    pub fn is_high(&self) -> bool {
        self.pin.gpio().pdir().read().pdi(self.n())
    }

    /// Get whether the pin input level is low.
    #[inline]
    pub fn is_low(&self) -> bool {
        !self.is_high()
    }

    /// Get the current pin input level.
    #[inline]
    pub fn level(&self) -> Level {
        self.is_high().into()
    }

    /// Is the output pin set as high?
    #[inline]
    pub fn output_is_high(&self) -> bool {
        self.pin.gpio().pdor().read().pdo(self.n())
    }

    /// Is the output pin set as low?
    #[inline]
    pub fn output_is_low(&self) -> bool {
        !self.output_is_high()
    }

    /// What level output is set to?
    #[inline]
    pub fn output_level(&self) -> Level {
        self.output_is_high().into()
    }

    /// Select open-drain (`true`) or push-pull (`false`) output.
    #[inline]
    pub fn set_open_drain(&mut self, open_drain: bool) {
        self.pin.set_open_drain(open_drain);
    }

    /// Configure the input logic inversion of this pin.
    #[inline]
    pub fn set_input_inversion(&mut self, invert: Inverter) {
        self.pin.set_input_inversion(invert);
    }

    /// Configure the pin's pull resistor.
    #[inline]
    pub fn set_pull(&mut self, pull: Pull) {
        self.pin.set_pull(pull);
    }

    /// Configure the pin's output drive strength.
    #[inline]
    pub fn set_drive_strength(&mut self, strength: DriveStrength) {
        self.pin.set_drive_strength(strength);
    }

    /// Configure the pin's output slew rate.
    #[inline]
    pub fn set_slew_rate(&mut self, slew_rate: SlewRate) {
        self.pin.set_slew_rate(slew_rate);
    }

    /// Enable or disable the pin's input buffer.
    #[inline]
    pub fn set_enable_input_buffer(&mut self, enabled: bool) {
        self.pin.set_enable_input_buffer(enabled);
    }
}

impl<'d> Drop for Flex<'d> {
    /// Returns the pin to its disconnected state.
    #[inline]
    fn drop(&mut self) {
        self.pin.set_as_disconnected();
    }
}

/// GPIO output driver.
pub struct Output<'d> {
    flex: Flex<'d>,
}

impl<'d> Output<'d> {
    /// Create a push-pull GPIO output driver for a pin with the provided initial
    /// output level, drive strength and slew rate.
    #[inline]
    pub fn new(pin: Peri<'d, impl Pin>, initial_output: Level, strength: DriveStrength, slew_rate: SlewRate) -> Self {
        let mut flex = Flex::new(pin);
        flex.set_level(initial_output);
        flex.set_open_drain(false);
        flex.set_drive_strength(strength);
        flex.set_slew_rate(slew_rate);
        flex.set_as_output();
        Self { flex }
    }

    /// Set the output as high.
    #[inline]
    pub fn set_high(&mut self) {
        self.flex.set_high();
    }

    /// Set the output as low.
    #[inline]
    pub fn set_low(&mut self) {
        self.flex.set_low();
    }

    /// Set the output level.
    #[inline]
    pub fn set_level(&mut self, level: Level) {
        self.flex.set_level(level);
    }

    /// Toggle the output level.
    #[inline]
    pub fn toggle(&mut self) {
        self.flex.toggle();
    }

    /// Is the output pin set as high?
    #[inline]
    pub fn output_is_high(&self) -> bool {
        self.flex.output_is_high()
    }

    /// Is the output pin set as low?
    #[inline]
    pub fn output_is_low(&self) -> bool {
        self.flex.output_is_low()
    }

    /// What level output is set to?
    #[inline]
    pub fn output_level(&self) -> Level {
        self.flex.output_level()
    }

    /// Return the underlying [`Flex`], to reconfigure the pin.
    #[inline]
    pub fn into_flex(self) -> Flex<'d> {
        self.flex
    }

    /// Convert into an open-drain output.
    #[inline]
    pub fn into_open_drain(mut self) -> OutputOpenDrain<'d> {
        self.flex.set_enable_input_buffer(true);
        self.flex.set_open_drain(true);
        OutputOpenDrain { flex: self.flex }
    }
}

/// GPIO open-drain output driver.
///
/// Driving high releases the line; the input half reads the line itself.
pub struct OutputOpenDrain<'d> {
    flex: Flex<'d>,
}

impl<'d> OutputOpenDrain<'d> {
    /// Create an open-drain GPIO output driver for a pin with the provided
    /// initial output level, drive strength and slew rate.
    #[inline]
    pub fn new(pin: Peri<'d, impl Pin>, initial_output: Level, strength: DriveStrength, slew_rate: SlewRate) -> Self {
        let mut flex = Flex::new(pin);
        flex.set_level(initial_output);
        flex.set_open_drain(true);
        flex.set_drive_strength(strength);
        flex.set_slew_rate(slew_rate);
        flex.set_as_output();
        flex.set_enable_input_buffer(true);
        Self { flex }
    }

    /// Set the output as high, releasing the line.
    #[inline]
    pub fn set_high(&mut self) {
        self.flex.set_high();
    }

    /// Set the output as low, driving the line low.
    #[inline]
    pub fn set_low(&mut self) {
        self.flex.set_low();
    }

    /// Set the output level.
    #[inline]
    pub fn set_level(&mut self, level: Level) {
        self.flex.set_level(level);
    }

    /// Toggle the output level.
    #[inline]
    pub fn toggle(&mut self) {
        self.flex.toggle();
    }

    /// Is the output pin set as high?
    #[inline]
    pub fn output_is_high(&self) -> bool {
        self.flex.output_is_high()
    }

    /// Is the output pin set as low?
    #[inline]
    pub fn output_is_low(&self) -> bool {
        self.flex.output_is_low()
    }

    /// What level output is set to?
    #[inline]
    pub fn output_level(&self) -> Level {
        self.flex.output_level()
    }

    /// Get whether the line is high.
    #[inline]
    pub fn is_high(&self) -> bool {
        self.flex.is_high()
    }

    /// Get whether the line is low.
    #[inline]
    pub fn is_low(&self) -> bool {
        self.flex.is_low()
    }

    /// Get the current line level.
    #[inline]
    pub fn level(&self) -> Level {
        self.flex.level()
    }

    /// Configure the input logic inversion of this pin.
    #[inline]
    pub fn set_input_inversion(&mut self, invert: Inverter) {
        self.flex.set_input_inversion(invert);
    }

    /// Return the underlying [`Flex`], to reconfigure the pin.
    #[inline]
    pub fn into_flex(self) -> Flex<'d> {
        self.flex
    }

    /// Convert into a push-pull output.
    #[inline]
    pub fn into_push_pull(mut self) -> Output<'d> {
        self.flex.set_open_drain(false);
        Output { flex: self.flex }
    }
}

