/// Macro to bind interrupts to handlers.
///
/// ```rust,ignore
/// use embassy_silabs::{bind_interrupts, peripherals};
///
/// bind_interrupts!(struct Irqs {
///     EUSART0_RX => eusart::RxInterruptHandler<peripherals::EUSART0>;
///     EUSART0_TX => eusart::TxInterruptHandler<peripherals::EUSART0>;
/// });
/// ```
#[macro_export]
macro_rules! bind_interrupts {
    ($(#[$outer:meta])* $vis:vis struct $name:ident {
        $(
            $(#[doc = $doc:literal])*
            $(#[cfg($cond_irq:meta)])?
            $irq:ident => $(
                $(#[cfg($cond_handler:meta)])?
                $handler:ty
            ),*;
        )*
    }) => {
        #[derive(Copy, Clone)]
        $(#[$outer])*
        $vis struct $name;

        $(
            #[allow(non_snake_case)]
            #[unsafe(no_mangle)]
            $(#[cfg($cond_irq)])?
            $(#[doc = $doc])*
            unsafe extern "C" fn $irq() {
                unsafe {
                    $(
                        $(#[cfg($cond_handler)])?
                        <$handler as $crate::interrupt::typelevel::Handler<$crate::interrupt::typelevel::$irq>>::on_interrupt();

                    )*
                }
            }

            $(#[cfg($cond_irq)])?
            $crate::bind_interrupts!(@inner
                $(
                    $(#[cfg($cond_handler)])?
                    unsafe impl $crate::interrupt::typelevel::Binding<$crate::interrupt::typelevel::$irq, $handler> for $name {}
                )*
            );
        )*
    };
    (@inner $($t:tt)*) => {
        $($t)*
    }
}

/// `embassy-silabs` global configuration.
#[non_exhaustive]
#[derive(Clone, Copy)]
pub struct Config {
    /// Clock tree.
    pub cmu: cmu::Config,
    /// Whether the debugger stays connected in EM2 (`EMU.CTRL.EM2DBGEN`). Default `true`.
    ///
    /// Series 0 has no such bit, so this field exists only on Series 2.
    #[cfg(silabs_series = "2")]
    pub enable_debug_during_sleep: bool,
    /// Priority of the GPIO interrupts (`GPIO_EVEN`, `GPIO_ODD`). Default `P0`.
    ///
    /// The GPIO `wait_for_*` functions use these interrupts.
    pub gpio_interrupt_priority: crate::interrupt::Priority,
    /// Priority of the time driver interrupt. Default `P0`.
    #[cfg(feature = "_time-driver")]
    pub time_interrupt_priority: crate::interrupt::Priority,
}

impl Default for Config {
    fn default() -> Self {
        Self {
            cmu: cmu::Config::new(),
            #[cfg(silabs_series = "2")]
            enable_debug_during_sleep: true,
            gpio_interrupt_priority: crate::interrupt::Priority::P0,
            #[cfg(feature = "_time-driver")]
            time_interrupt_priority: crate::interrupt::Priority::P0,
        }
    }
}

/// Initializes embassy and returns the peripheral singletons for creating drivers.
///
/// # Panics
///
/// Panics on a second call.
pub fn init(config: Config) -> Peripherals {
    critical_section::with(|cs| {
        let peripherals = Peripherals::take_with_cs(cs);

        // EMU has no CMU clock gate.
        #[cfg(silabs_series = "2")]
        pac::EMU
            .ctrl()
            .modify(|w| w.set_em2dbgen(config.enable_debug_during_sleep));

        cmu::init_clocks(cs, config.cmu);
        gpio::init(config.gpio_interrupt_priority);

        #[cfg(feature = "_time-driver")]
        time_driver::init(cs, config.time_interrupt_priority);

        peripherals
    })
}
