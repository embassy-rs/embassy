//! Generates peripheral, interrupt and CMU code from `silabs_metapac::metadata::METADATA`.
//!
//! - Singletons for each peripheral and bonded pin. The time driver's timer has a type but no
//!   `Peripherals` field, because the driver owns it.
//! - `cmu::SealedCmuPeripheral` for each peripheral with CMU data, and `cmu::Clocks`, group clock
//!   functions and `cmu::mux::ClockMux` in `$OUT_DIR/_cmu_mux.rs`.
//! - `interrupt_mod!` for each NVIC vector.
//! - `foreach_peripheral!`, `foreach_interrupt!` and `foreach_pin!` in `$OUT_DIR/_macros.rs`.
//! - `impl_eusart!` (Series 2) or `impl_usart!` (Series 0), with `pin_trait_impl!` for their pins.
//! - `timer::Instance` impls, 16-bit or 32-bit by metadata `block`.
//! - Metapac chip cfgs. Code that depends on register shape uses version cfgs (`hfxo_s2v2`,
//!   `sysrtc`). Use `silabs_series_2_config = "<M>"` only for errata and family-specific tables.
//!
//! - Read the per-chip metadata exposed by `silabs-metapac` once the
//!   chip's Cargo feature is enabled.
//! - For every peripheral instance, emit a singleton in
//!   `embassy_hal_internal::peripherals_definition!{…}` (so the type
//!   exists) and `embassy_hal_internal::peripherals_struct!{…}` (so
//!   `init()` returns it in `Peripherals`).
//! - The chosen time-driver timer (`time-driver-timer0`, etc.) is
//!   present in `peripherals_definition!` but skipped from
//!   `peripherals_struct!` — the time driver owns it.
//! - For every peripheral with CMU data (`cmu`, like stm32-metapac's
//!   `rcc`), emit `cmu::SealedCmuPeripheral` with `enable_bus_clock()`,
//!   `disable_bus_clock()` and the kernel-clock `frequency()`. Write
//!   `cmu::Clocks`, the group-clock frequency functions and
//!   `cmu::mux::ClockMux` (one field per group and peripheral clock
//!   select) to `$OUT_DIR/_cmu_mux.rs`.
//! - Emit `interrupt_mod!{…}` for every NVIC vector the chip exposes.
//! - Emit the `foreach_peripheral!`, `foreach_interrupt!` and
//!   `foreach_pin!` table macros to `$OUT_DIR/_macros.rs`, like
//!   embassy-stm32, and the `impl_eusart!` invocations. Interrupts come
//!   from `Peripheral.interrupts` and pins from `METADATA.pins`.
//! - Emit the `timer::Instance` impls, with `Instance16bit` or
//!   `Instance32bit` chosen by the metadata `block`.
//! - Forward the metapac chip cfgs. Gate code that depends on register
//!   shape on version cfgs (`hfxo_s2v2`, `sysrtc`). Use
//!   `silabs_series_2_config = "<M>"` only for errata and per-family
//!   characterization.
//!
//! `$OUT_DIR/_generated.rs` and `$OUT_DIR/_macros.rs` are included from
//! `src/lib.rs`.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::PathBuf;
use std::{env, fs};

use silabs_metapac::metadata::ir::{BlockItemInner, IR};
use silabs_metapac::metadata::{METADATA, Peripheral, PeripheralCmuKernelClock, PeripheralCmuRegister};

fn main() {
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR not set"));
    let out_path = out_dir.join("_generated.rs");

    let mut out = String::new();
    out.push_str("// Generated by embassy-silabs/build.rs. Do not edit.\n\n");

    let mut singletons: Vec<String> = Vec::new();
    for p in METADATA.peripherals {
        if skip_peripheral_kind(p.kind) {
            continue;
        }
        singletons.push(p.name.to_string());
    }

    let pins: Vec<(String, u8)> = METADATA
        .pins
        .iter()
        .map(|p| (p.name.to_string(), p.port * 16 + p.pin))
        .collect();
    singletons.extend(pins.iter().map(|(name, _)| name.clone()));

    // Sort for stable output.
    singletons.sort();
    singletons.dedup();

    let time_driver = match env::vars()
        .map(|(a, _)| a)
        .filter(|x| x.starts_with("CARGO_FEATURE_TIME_DRIVER_"))
        .get_one()
    {
        Ok(x) => Some(
            x.strip_prefix("CARGO_FEATURE_TIME_DRIVER_")
                .unwrap()
                .to_ascii_lowercase(),
        ),
        Err(GetOneError::None) => None,
        Err(GetOneError::Multiple) => panic!("Multiple time-driver-xxx Cargo features enabled"),
    };

    // The time driver needs a 32-bit counter. The metadata block is `Timer32` for a wide timer and
    // `Timer` for a 16-bit one (TIMER1 on MG22).
    let is_wide = |name: &str| {
        METADATA
            .peripherals
            .iter()
            .any(|p| p.name == name && p.block == "Timer32")
    };
    let time_driver_singleton = match time_driver.as_ref().map(|x| x.as_ref()) {
        None => "",
        Some(t @ ("timer0" | "timer1")) => {
            let name = if t == "timer0" { "TIMER0" } else { "TIMER1" };
            if !is_wide(name) {
                panic!("time-driver-{t} requested, but {name} on this chip is not a 32-bit TIMER");
            }
            name
        }
        Some("any") => ["TIMER0", "TIMER1"]
            .into_iter()
            .find(|tim| is_wide(tim))
            .expect("time-driver-any requested, but the chip has no 32-bit TIMER0 or TIMER1."),
        _ => panic!("unknown time_driver {:?}", time_driver),
    };

    if !time_driver_singleton.is_empty() {
        println!(
            "cargo:rustc-cfg=time_driver_{}",
            time_driver_singleton.to_ascii_lowercase()
        );
    }
    for tim in ["timer0", "timer1"] {
        println!("cargo:rustc-check-cfg=cfg(time_driver_{tim})");
    }

    writeln!(out, "embassy_hal_internal::peripherals_definition!(").unwrap();
    for s in &singletons {
        writeln!(out, "    {s},").unwrap();
    }
    writeln!(out, ");\n").unwrap();

    // Emit the CMU impls for every singleton with a CMU gate in the
    // metadata (`cmu`, like stm32-metapac's `rcc`):
    // - `enable_bus_clock()` / `disable_bus_clock()` write the gate's SET /
    //   CLR alias: one write, no read-modify-write race. A gate that several
    //   singletons share gets a refcount, like embassy-stm32: the first
    //   enable sets it and the last disable clears it.
    // - `frequency()` returns the kernel clock. A fixed clock reads the
    //   frozen `Clocks` table. A mux reads the select field at run time and
    //   maps each enum variant to a `Clocks` field.
    let cmu_ir = METADATA
        .peripherals
        .iter()
        .find(|p| p.kind == "cmu")
        .expect("chip has no CMU")
        .ir;
    let gated: Vec<_> = METADATA
        .peripherals
        .iter()
        .filter(|p| singletons.iter().any(|s| s == p.name))
        .filter_map(|p| {
            let cmu = p.cmu.as_ref()?;
            Some((p, cmu, cmu.enable.as_ref()?))
        })
        .collect();
    let mut gate_count: BTreeMap<(&str, &str), usize> = BTreeMap::new();
    for (_, _, en) in &gated {
        *gate_count.entry((en.register, en.field)).or_default() += 1;
    }
    let refcount_name = |reg: &str, field: &str| format!("{reg}_{field}").to_ascii_uppercase();
    let shared: Vec<_> = gate_count.iter().filter(|(_, n)| **n > 1).map(|(k, _)| *k).collect();
    if !shared.is_empty() {
        writeln!(out, "mod cmu_refcount {{").unwrap();
        for (reg, field) in &shared {
            writeln!(
                out,
                "    pub(crate) static {}: critical_section::Mutex<core::cell::Cell<u8>> = \
                 critical_section::Mutex::new(core::cell::Cell::new(0));",
                refcount_name(reg, field)
            )
            .unwrap();
        }
        writeln!(out, "}}\n").unwrap();
    }
    let mut muxes: BTreeSet<(String, String, String)> = BTreeSet::new();
    for (p, cmu, en) in gated {
        let set = format!(
            "crate::pac::CMU.{}_set().write(|w| w.set_{}(true));",
            en.register, en.field
        );
        let clr = format!(
            "crate::pac::CMU.{}_clr().write(|w| w.set_{}(true));",
            en.register, en.field
        );
        let (enable, disable) = if shared.contains(&(en.register, en.field)) {
            let count = format!(
                "let count = crate::cmu_refcount::{}.borrow(cs);",
                refcount_name(en.register, en.field)
            );
            (
                format!(
                    "critical_section::with(|cs| {{\n            {count}\n            \
                     if count.get() == 0 {{\n                {set}\n            }}\n            \
                     count.set(count.get().checked_add(1).expect(\"{name}: CMU gate refcount overflow\"));\n        }});",
                    name = p.name,
                ),
                format!(
                    "critical_section::with(|cs| {{\n            {count}\n            \
                     assert!(count.get() > 0, \"{name}: CMU gate disabled more often than enabled\");\n            \
                     count.set(count.get() - 1);\n            \
                     if count.get() == 0 {{\n                {clr}\n            }}\n        }});",
                    name = p.name,
                ),
            )
        } else {
            (set, clr)
        };
        let frequency = match &cmu.kernel_clock {
            None => format!("panic!(\"peripheral '{}' has no kernel clock\")", p.name),
            Some(PeripheralCmuKernelClock::Clock(clock)) => clock_expr(p.name, clock, 1),
            Some(PeripheralCmuKernelClock::Mux(mux)) => {
                let enum_name = mux_enum(cmu_ir, mux);
                muxes.insert((mux.register.to_string(), mux.field.to_string(), enum_name.clone()));
                mux_expr(p.name, cmu_ir, mux, &enum_name)
            }
        };
        writeln!(
            out,
            "impl crate::cmu::SealedCmuPeripheral for peripherals::{name} {{\n    \
             fn enable_bus_clock() {{\n        \
             {enable}\n    \
             }}\n    \
             fn disable_bus_clock() {{\n        \
             {disable}\n    \
             }}\n    \
             fn frequency() -> crate::time::Hertz {{\n        \
             {frequency}\n    \
             }}\n}}\nimpl crate::cmu::CmuPeripheral for peripherals::{name} {{}}\n",
            name = p.name,
        )
        .unwrap();
    }
    writeln!(out).unwrap();
    // `cmu/mod.rs` includes this file, so the mux module is `cmu::mux`.
    let mut mux_out = String::from("// Generated by embassy-silabs/build.rs. Do not edit.\n\n");
    write_clocks(&mut mux_out);
    let mut mux_fields = Vec::new();
    for &(register, name) in GROUP_MUXES {
        let mux = PeripheralCmuRegister {
            register,
            field: "clksel",
        };
        let Some(enum_name) = find_mux_enum(cmu_ir, &mux) else {
            continue;
        };
        if CLOCKS.contains(&name) {
            write_group_freq(&mut mux_out, cmu_ir, name, &mux, &enum_name);
        }
        mux_fields.push((name.to_string(), register.to_string(), "clksel".to_string(), enum_name));
    }
    write_fill_group_freqs(&mut mux_out, &mux_fields);
    for (reg, field, e) in &muxes {
        mux_fields.push((mux_field_name(reg, field), reg.clone(), field.clone(), e.clone()));
    }
    write_clock_mux(&mut mux_out, &mux_fields);
    fs::write(out_dir.join("_cmu_mux.rs"), &mux_out).expect("write _cmu_mux.rs");

    writeln!(out, "embassy_hal_internal::peripherals_struct!(").unwrap();
    for s in &singletons {
        if s == time_driver_singleton {
            // The time driver owns it: keep the type, drop the field.
            continue;
        }
        writeln!(out, "    {s},").unwrap();
    }
    writeln!(out, ");\n").unwrap();

    // The generator already dedups `METADATA.interrupts`. This is a safeguard.
    let mut seen: BTreeSet<&str> = BTreeSet::new();
    let mut irq_names: Vec<&str> = Vec::new();
    for i in METADATA.interrupts {
        if seen.insert(i.name) {
            irq_names.push(i.name);
        }
    }
    writeln!(out, "embassy_hal_internal::interrupt_mod!(").unwrap();
    for name in &irq_names {
        writeln!(out, "    {name},").unwrap();
    }
    writeln!(out, ");\n").unwrap();

    let tables = Tables::new(&singletons, &pins);
    let mut macros = String::from("// Generated by embassy-silabs/build.rs. Do not edit.\n\n");
    make_table(&mut macros, "foreach_peripheral", &tables.peripherals);
    make_table(&mut macros, "foreach_interrupt", &tables.interrupts);
    make_table(&mut macros, "foreach_pin", &tables.pins);
    fs::write(out_dir.join("_macros.rs"), &macros).expect("write _macros.rs");

    write_eusart_impls(&mut out);
    write_timer_impls(&mut out, &singletons);

    if !time_driver_singleton.is_empty() {
        let timer = METADATA
            .peripherals
            .iter()
            .find(|p| p.name == time_driver_singleton)
            .unwrap();
        let irq = irq(timer, "GLOBAL");
        writeln!(out).unwrap();
        writeln!(out, "#[cfg(feature = \"rt\")]").unwrap();
        writeln!(out, "#[interrupt]").unwrap();
        writeln!(out, "fn {irq}() {{").unwrap();
        writeln!(out, "    crate::time_driver::get_driver().on_interrupt();").unwrap();
        writeln!(out, "}}").unwrap();
    }

    fs::write(&out_path, &out).expect("write _generated.rs");

    // Chip cfgs from silabs-metapac `links` metadata: `silabs_series="2"`,
    // `silabs_series_2_config="6"` (MG26), and per peripheral `<kind>`, `<kind>_<version>` and its
    // prefixes (`timer_s2`, `timer_s2v0`). `rerun-if-changed=build.rs` turns off the default rerun
    // rules, so the metapac variables need their own rule, or the cfgs go stale.
    let dep = |key: &str| {
        println!("cargo:rerun-if-env-changed=DEP_SILABS_METAPAC_{key}");
        env::var(format!("DEP_SILABS_METAPAC_{key}"))
            .unwrap_or_else(|_| panic!("DEP_SILABS_METAPAC_{key} not set; silabs-metapac >= 0.6 is required"))
    };
    for spec in dep("CHECK_CFGS").split_ascii_whitespace() {
        println!("cargo:rustc-check-cfg={spec}");
    }
    for cfg in dep("CFGS").split_ascii_whitespace() {
        println!("cargo:rustc-cfg={cfg}");
    }

    println!("cargo:rerun-if-changed=build.rs");
}

/// `Clocks` fields that `cmu::init_clocks` fills in. A mux source that is
/// not in this list (an external pin, CLKIN0, a PLL) makes `frequency()`
/// panic when the mux selects it.
const CLOCKS: &[&str] = &[
    "hfxo",
    "hfrcodpll",
    "hfrcoem23",
    "fsrco",
    "lfxo",
    "lfrco",
    "ulfrco",
    "sysclk",
    "hclk",
    "pclk",
    "lspclk",
    "em01grpaclk",
    "em01grpbclk",
    "em01grpcclk",
    "em23grpaclk",
    "em4grpaclk",
];

/// Returns `clock` frequency divided by `div`, read from the frozen `Clocks` table.
fn clock_expr(peripheral: &str, clock: &str, div: u32) -> String {
    assert!(
        CLOCKS.contains(&clock),
        "{peripheral}: kernel clock `{clock}` is not a cmu::Clocks field"
    );
    let div = if div == 1 {
        String::new()
    } else {
        format!(" / {div}u32")
    };
    format!(
        "unwrap!(unsafe {{ crate::cmu::get_freqs() }}.{clock}, \
         \"peripheral '{{}}' uses the '{{}}' clock, which is not running\", {peripheral:?}, {clock:?}){div}"
    )
}

/// Maps a mux enum variant to `(Clocks field, divider)`.
///
/// Returns `None` for `Disabled` and for sources that `init_clocks` does not track.
fn mux_source(variant: &str) -> Option<(String, u32)> {
    let v = variant.to_ascii_lowercase();
    if v.starts_with("disable") {
        return None;
    }
    // `Hfxort` and `Hfrcodpllrt` are retimed copies of `Hfxo` and `Hfrcodpll`.
    let v = match v.strip_suffix("rt") {
        Some(base) if CLOCKS.contains(&base) => base.to_owned(),
        _ => v,
    };
    // `Hclkdiv1024` is HCLK / 1024.
    let (v, div) = match v.split_once("div") {
        Some((base, div)) if div.parse::<u32>().is_ok() => (base.to_owned(), div.parse().unwrap()),
        _ => (v, 1),
    };
    CLOCKS.contains(&v.as_str()).then_some((v, div))
}

/// Returns the enum name for a CMU select field.
fn mux_enum(ir: &IR, mux: &PeripheralCmuRegister) -> String {
    find_mux_enum(ir, mux)
        .unwrap_or_else(|| panic!("CMU has no select field {}.{} with an enum", mux.register, mux.field))
}

/// Returns the enum name for a CMU select field.
///
/// Returns `None` when the register, field or enum is missing on this chip.
fn find_mux_enum(ir: &IR, mux: &PeripheralCmuRegister) -> Option<String> {
    let block = ir
        .blocks
        .iter()
        .find(|b| b.name == "Cmu")
        .expect("CMU IR has no Cmu block");
    let item = block.items.iter().find(|i| i.name == mux.register)?;
    let BlockItemInner::Register(reg) = &item.inner else {
        return None;
    };
    let fs = ir.fieldsets.iter().find(|f| Some(f.name) == reg.fieldset)?;
    let field = fs.fields.iter().find(|f| f.name == mux.field)?;
    field.enumm.map(str::to_string)
}

/// Returns a `match` on the current value of a mux select field.
fn mux_expr(peripheral: &str, ir: &IR, mux: &PeripheralCmuRegister, enum_name: &str) -> String {
    let e = ir.enums.iter().find(|e| e.name == enum_name).unwrap();
    let mut arms = String::new();
    for v in e.variants {
        if let Some((clock, div)) = mux_source(v.name) {
            let expr = clock_expr(peripheral, &clock, div);
            writeln!(
                arms,
                "            crate::pac::cmu::vals::{enum_name}::{} => {{\n                {expr}\n            }}",
                v.name
            )
            .unwrap();
        }
    }
    format!(
        "match crate::pac::CMU.{reg}().read().{field}() {{\n\
         {arms}            \
         #[allow(unreachable_patterns)]\n            \
         _ => panic!(\"peripheral '{{}}' uses a clock source that embassy-silabs does not track\", {peripheral:?}),\n        \
         }}",
        reg = mux.register,
        field = mux.field,
    )
}

/// Returns the `ClockMux` field name for a select field: `eusart0clkctrl.clksel` becomes `eusart0`.
fn mux_field_name(register: &str, field: &str) -> String {
    let name = if field == "clksel" {
        register.strip_suffix("clkctrl")
    } else {
        field.strip_suffix("clksel")
    };
    name.unwrap_or_else(|| panic!("cannot name mux {register}.{field}"))
        .to_owned()
}

/// CMU group clock selects that go into `ClockMux`.
///
/// The second name is the `ClockMux` field and, where it is a `Clocks` field, the clock it drives.
const GROUP_MUXES: &[(&str, &str)] = &[
    ("em01grpaclkctrl", "em01grpaclk"),
    ("em01grpbclkctrl", "em01grpbclk"),
    ("em01grpcclkctrl", "em01grpcclk"),
    ("em23grpaclkctrl", "em23grpaclk"),
    ("em4grpaclkctrl", "em4grpaclk"),
    ("traceclkctrl", "traceclk"),
];

/// `cmu::Clocks`, one `Option<Hertz>` field per entry of [`CLOCKS`].
fn write_clocks(out: &mut String) {
    writeln!(
        out,
        "/// Frozen clock tree frequencies, set once by `init_clocks`.\n\
         ///\n\
         /// Field names match metapac `kernel_clock` names.\n\
         /// `None` means the clock is off or missing.\n\
         #[derive(Copy, Clone, Default, Eq, PartialEq, Debug)]\n\
         #[cfg_attr(feature = \"defmt\", derive(defmt::Format))]\n\
         #[non_exhaustive]\n\
         pub struct Clocks {{"
    )
    .unwrap();
    for clock in CLOCKS {
        writeln!(out, "    pub {clock}: Option<Hertz>,").unwrap();
    }
    writeln!(out, "}}\n").unwrap();
}

/// Writes `<name>_freq()`, which returns a group clock frequency.
///
/// The frequency comes from the current select value and the base clocks in `c`.
fn write_group_freq(out: &mut String, ir: &IR, name: &str, mux: &PeripheralCmuRegister, enum_name: &str) {
    let e = ir.enums.iter().find(|e| e.name == enum_name).unwrap();
    writeln!(
        out,
        "pub(crate) fn {name}_freq(c: &Clocks) -> Option<Hertz> {{\n    \
         #[allow(unreachable_patterns)]\n    \
         match crate::pac::CMU.{reg}().read().{field}() {{",
        reg = mux.register,
        field = mux.field,
    )
    .unwrap();
    for v in e.variants {
        let Some((clock, div)) = mux_source(v.name) else {
            continue;
        };
        let div = if div == 1 {
            String::new()
        } else {
            format!(".map(|f| f / {div}u32)")
        };
        writeln!(
            out,
            "        crate::pac::cmu::vals::{enum_name}::{} => c.{clock}{div},",
            v.name
        )
        .unwrap();
    }
    writeln!(out, "        _ => None,\n    }}\n}}\n").unwrap();
}

/// `fill_group_freqs()`: fills every group clock of this chip in `c`.
fn write_fill_group_freqs(out: &mut String, fields: &[(String, String, String, String)]) {
    writeln!(out, "pub(crate) fn fill_group_freqs(c: &mut Clocks) {{").unwrap();
    for (name, ..) in fields.iter().filter(|(name, ..)| CLOCKS.contains(&name.as_str())) {
        writeln!(out, "    c.{name} = {name}_freq(c);").unwrap();
    }
    writeln!(out, "}}\n").unwrap();
}

/// Writes `cmu::mux::ClockMux`, with one field per group and peripheral clock select.
///
/// `muxes` holds `(field, register, select field, enum)`. `init` writes only the `Some` fields.
fn write_clock_mux(out: &mut String, muxes: &[(String, String, String, String)]) {
    let enums: BTreeSet<&str> = muxes.iter().map(|(_, _, _, e)| e.as_str()).collect();
    writeln!(out, "pub mod mux {{").unwrap();
    for e in &enums {
        writeln!(out, "    pub use crate::pac::cmu::vals::{e};").unwrap();
    }
    writeln!(
        out,
        "\n    /// Group and peripheral clock selects. `init` writes only the `Some` fields.\n    \
         #[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]\n    \
         #[cfg_attr(feature = \"defmt\", derive(defmt::Format))]\n    \
         #[non_exhaustive]\n    \
         pub struct ClockMux {{"
    )
    .unwrap();
    for (name, _, _, e) in muxes {
        writeln!(out, "        pub {name}: Option<{e}>,").unwrap();
    }
    writeln!(
        out,
        "    }}\n\n    impl ClockMux {{\n        pub const fn new() -> Self {{\n            Self {{"
    )
    .unwrap();
    for (name, ..) in muxes {
        writeln!(out, "                {name}: None,").unwrap();
    }
    writeln!(
        out,
        "            }}\n        }}\n\n        pub(crate) fn init(&self) {{"
    )
    .unwrap();
    for (name, reg, field, _) in muxes {
        writeln!(
            out,
            "            if let Some(v) = self.{name} {{\n                \
             crate::pac::CMU.{reg}().modify(|w| w.set_{field}(v));\n            \
             }}"
        )
        .unwrap();
    }
    writeln!(out, "        }}\n    }}\n}}\n").unwrap();
}

/// Rows for the `foreach_*!` table macros.
struct Tables {
    /// `(kind, NAME)` per singleton peripheral.
    peripherals: Vec<Vec<String>>,
    /// `(NAME, kind, SIGNAL, IRQ)` per interrupt that belongs to a peripheral.
    interrupts: Vec<Vec<String>>,
    /// `(PIN, port * 16 + pin)` per GPIO pin.
    pins: Vec<Vec<String>>,
}

impl Tables {
    fn new(singletons: &[String], pins: &[(String, u8)]) -> Self {
        let peris: Vec<_> = METADATA
            .peripherals
            .iter()
            .filter(|p| singletons.iter().any(|s| s == p.name))
            .collect();
        let peripherals = peris
            .iter()
            .map(|p| vec![p.kind.to_string(), p.name.to_string()])
            .collect();

        let interrupts = peris
            .iter()
            .flat_map(|p| {
                p.interrupts.iter().map(|i| {
                    vec![
                        p.name.to_string(),
                        p.kind.to_string(),
                        i.signal.to_string(),
                        i.interrupt.to_string(),
                    ]
                })
            })
            .collect();

        let pins = pins.iter().map(|(name, n)| vec![name.clone(), n.to_string()]).collect();
        Self {
            peripherals,
            interrupts,
            pins,
        }
    }
}

/// Writes a table macro.
///
/// The caller's arms become an inner macro that runs once per row. When a row matches no arm, the
/// macro expands to nothing.
fn make_table(out: &mut String, name: &str, data: &[Vec<String>]) {
    write!(
        out,
        "#[allow(unused)]
macro_rules! {} {{
    ($($pat:tt => $code:tt;)*) => {{
        macro_rules! __{}_inner {{
            $(($pat) => $code;)*
            ($_:tt) => {{}}
        }}
",
        name, name
    )
    .unwrap();

    for row in data {
        writeln!(out, "        __{}_inner!(({}));", name, row.join(",")).unwrap();
    }

    writeln!(
        out,
        "    }};
}}"
    )
    .unwrap();
}

/// Writes `impl_eusart!` per EUSART.
///
/// `macro_rules!` cannot join identifiers, so the interrupt and GPIO route names are spelled out.
fn write_eusart_impls(out: &mut String) {
    let gpio_items: Vec<&str> = METADATA
        .peripherals
        .iter()
        .find(|p| p.name == "GPIO")
        .map(|p| {
            p.ir.blocks
                .iter()
                .flat_map(|b| b.items.iter().map(|i| i.name))
                .collect()
        })
        .unwrap_or_default();
    for p in METADATA.peripherals.iter().filter(|p| p.kind == "eusart") {
        let route = |suffix: &str| {
            let name = format!("{}_{suffix}", p.name.to_ascii_lowercase());
            assert!(gpio_items.contains(&name.as_str()), "GPIO has no {name} register");
            name
        };
        writeln!(
            out,
            "crate::eusart::impl_eusart!({}, {}, {}, {}, {}, {});",
            p.name,
            irq(p, "RX"),
            irq(p, "TX"),
            route("txroute"),
            route("rxroute"),
            route("routeen"),
        )
        .unwrap();
    }
    writeln!(out).unwrap();
}

/// Writes `timer::Instance` and the counter width trait per TIMER singleton.
fn write_timer_impls(out: &mut String, singletons: &[String]) {
    for p in METADATA
        .peripherals
        .iter()
        .filter(|p| p.kind == "timer" && singletons.iter().any(|s| s == p.name))
    {
        let (level, f, block) = match p.block {
            "Timer32" => ("Instance32bit", "regs_32bit", "Timer32"),
            "Timer" => ("Instance16bit", "regs_16bit", "Timer"),
            b => panic!("{}: unknown TIMER block {b}", p.name),
        };
        writeln!(
            out,
            "impl crate::timer::SealedInstance for peripherals::{name} {{}}\n\
             impl crate::timer::Instance for peripherals::{name} {{\n    \
             type Interrupt = crate::interrupt::typelevel::{irq};\n}}\n\
             impl crate::timer::{level} for peripherals::{name} {{\n    \
             fn {f}() -> crate::pac::timer::{block} {{\n        \
             crate::pac::{name}\n    \
             }}\n}}\n",
            name = p.name,
            irq = irq(p, "GLOBAL"),
        )
        .unwrap();
    }
}

/// Returns the IRQ for `signal` (`GLOBAL`, `RX`) on `p`, from `Peripheral.interrupts`.
fn irq(p: &Peripheral, signal: &str) -> &'static str {
    p.interrupts
        .iter()
        .find(|i| i.signal == signal)
        .map(|i| i.interrupt)
        .unwrap_or_else(|| panic!("{} has no {signal} interrupt", p.name))
}

/// Skip kinds that don't make sense as embassy peripheral singletons.
/// Conservative — only DEVINFO is dropped (read-only chip identity, not
/// a controllable peripheral). Security / mailbox / config peripherals
/// stay in so HALs can grow drivers for them without revisiting this list.
fn skip_peripheral_kind(kind: &str) -> bool {
    matches!(kind, "devinfo")
}

enum GetOneError {
    None,
    Multiple,
}

trait IteratorExt: Iterator {
    fn get_one(self) -> Result<Self::Item, GetOneError>;
}

impl<T: Iterator> IteratorExt for T {
    fn get_one(mut self) -> Result<Self::Item, GetOneError> {
        match self.next() {
            None => Err(GetOneError::None),
            Some(res) => match self.next() {
                Some(_) => Err(GetOneError::Multiple),
                None => Ok(res),
            },
        }
    }
}
