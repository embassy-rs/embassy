//! Generates peripheral, interrupt and CMU code from `silabs_metapac::metadata::METADATA`.
//!
//! - Singletons for each peripheral and bonded pin. The time driver's timer has a type but no
//!   `Peripherals` field, because the driver owns it.
//! - `cmu::SealedCmuPeripheral` for each peripheral with CMU data, and `cmu::Clocks`, group clock
//!   functions and `cmu::mux::ClockMux` in `$OUT_DIR/_cmu_mux.rs`.
//! - `interrupt_mod!` for each NVIC vector.
//! - `foreach_peripheral!`, `foreach_interrupt!` and `foreach_pin!` in `$OUT_DIR/_macros.rs`.
//! - `impl_eusart!` (Series 2) or `impl_usart!` (Series 0), with `pin_trait_impl!` for their pins.
//! - `timer::Instance` impls, 16-bit or 32-bit by metadata `block`.
//! - Metapac chip cfgs. Code that depends on register shape uses version cfgs (`hfxo_s2v2`,
//!   `sysrtc`). Use `silabs_series_2_config = "<M>"` only for errata and family-specific tables.
//!
//! - Read the per-chip metadata exposed by `silabs-metapac` once the
//!   chip's Cargo feature is enabled.
//! - For every peripheral instance, emit a singleton in
//!   `embassy_hal_internal::peripherals_definition!{…}` (so the type
//!   exists) and `embassy_hal_internal::peripherals_struct!{…}` (so
//!   `init()` returns it in `Peripherals`).
//! - The chosen time-driver timer (`time-driver-timer0`, etc.) is
//!   present in `peripherals_definition!` but skipped from
//!   `peripherals_struct!` — the time driver owns it.
//! - For every peripheral with CMU data (`cmu`, like stm32-metapac's
//!   `rcc`), emit `cmu::SealedCmuPeripheral` with `enable_bus_clock()` and
//!   the kernel-clock `frequency()`, and write `cmu::mux::ClockMux` with one
//!   field per peripheral clock select to `$OUT_DIR/_cmu_mux.rs`.
//! - Emit `interrupt_mod!{…}` for every NVIC vector the chip exposes.
//! - GPIO pins are not yet in the PAC metadata. Series 2 has a
//!   stable port-A..D / 16 pins-per-port layout — hard-code those
//!   here until the data pipeline grows a pin extraction stage.
//! - Emit `cargo:rustc-cfg=silabs_series_<N>_config="<M>"` from the
//!   chip's `_SILICON_LABS_32B_SERIES_<N>_CONFIG_<M>` so HAL source can
//!   gate per-family erratas with
//!   `#[cfg(silabs_series_2_config = "...")]`.
//!
//! The generated file lives at `$OUT_DIR/_generated.rs` and is included
//! from `src/lib.rs` via `include!(concat!(env!("OUT_DIR"), "/_generated.rs"))`.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::PathBuf;
use std::{env, fs};

use silabs_metapac::metadata::ir::{BlockItemInner, IR};
use silabs_metapac::metadata::{METADATA, PeripheralCmuKernelClock, PeripheralCmuRegister};

fn main() {
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR not set"));
    let out_path = out_dir.join("_generated.rs");

    let mut out = String::new();
    out.push_str("// Generated by embassy-silabs/build.rs. Do not edit.\n\n");

    // Singleton names: peripheral instances (filtered to those worth
    // exposing) followed by GPIO pins.
    // 1. Peripheral instances.
    let mut singletons: Vec<String> = Vec::new();
    for p in METADATA.peripherals {
        if skip_peripheral_kind(p.kind) {
            continue;
        }
        singletons.push(p.name.to_string());
    }

    // 2. GPIO pins. Series 2 layout is ports A..D × 16 pins each. The
    //    largest currently-supported chip (EFR32MG26 IM68) exposes all
    //    of these; smaller packages physically bond fewer, but the
    //    silicon block is uniform — keeping the full set in the type
    //    system just means a few unused singletons on smaller parts.
    if METADATA.peripherals.iter().any(|p| p.name == "GPIO") {
        for port in &['A', 'B', 'C', 'D'] {
            for pin in 0..16 {
                singletons.push(format!("P{port}{pin:02}"));
            }
        }
    }

    // Sort for stable output.
    singletons.sort();
    singletons.dedup();

    let time_driver = match env::vars()
        .map(|(a, _)| a)
        .filter(|x| x.starts_with("CARGO_FEATURE_TIME_DRIVER_"))
        .get_one()
    {
        Ok(x) => Some(
            x.strip_prefix("CARGO_FEATURE_TIME_DRIVER_")
                .unwrap()
                .to_ascii_lowercase(),
        ),
        Err(GetOneError::None) => None,
        Err(GetOneError::Multiple) => panic!("Multiple time-driver-xxx Cargo features enabled"),
    };

    // The time driver needs a 32-bit counter: the metadata block is
    // `TIMER32` for wide timers and `TIMER` for 16-bit ones (TIMER1 on MG22).
    let is_wide = |name: &str| {
        METADATA
            .peripherals
            .iter()
            .any(|p| p.name == name && p.block == "TIMER32")
    };
    let time_driver_singleton = match time_driver.as_ref().map(|x| x.as_ref()) {
        None => "",
        Some(t @ ("timer0" | "timer1")) => {
            let name = if t == "timer0" { "TIMER0" } else { "TIMER1" };
            if !is_wide(name) {
                panic!("time-driver-{t} requested, but {name} on this chip is not a 32-bit TIMER");
            }
            name
        }
        Some("any") => ["TIMER0", "TIMER1"]
            .into_iter()
            .find(|tim| is_wide(tim))
            .expect("time-driver-any requested, but the chip has no 32-bit TIMER0 or TIMER1."),
        _ => panic!("unknown time_driver {:?}", time_driver),
    };

    if !time_driver_singleton.is_empty() {
        println!(
            "cargo:rustc-cfg=time_driver_{}",
            time_driver_singleton.to_ascii_lowercase()
        );
    }
    for tim in ["timer0", "timer1"] {
        println!("cargo:rustc-check-cfg=cfg(time_driver_{tim})");
    }

    writeln!(out, "embassy_hal_internal::peripherals_definition!(").unwrap();
    for s in &singletons {
        writeln!(out, "    {s},").unwrap();
    }
    writeln!(out, ");\n").unwrap();

    // Emit the CMU impls for every singleton with a CMU gate in the
    // metadata (`cmu`, like stm32-metapac's `rcc`):
    // - `enable_bus_clock()` sets the gate through the register's SET alias:
    //   one write, no read-modify-write race.
    // - `frequency()` returns the kernel clock. A fixed clock reads the
    //   frozen `Clocks` table. A mux reads the select field at run time and
    //   maps each enum variant to a `Clocks` field.
    let cmu_ir = METADATA
        .peripherals
        .iter()
        .find(|p| p.kind == "cmu")
        .expect("chip has no CMU")
        .ir;
    let mut muxes: BTreeSet<(String, String, String)> = BTreeSet::new();
    for p in METADATA.peripherals {
        let Some(cmu) = &p.cmu else { continue };
        let Some(en) = &cmu.enable else { continue };
        if !singletons.iter().any(|s| s == p.name) {
            continue;
        }
        let frequency = match &cmu.kernel_clock {
            None => format!("panic!(\"peripheral '{}' has no kernel clock\")", p.name),
            Some(PeripheralCmuKernelClock::Clock(clock)) => clock_expr(p.name, clock, 1),
            Some(PeripheralCmuKernelClock::Mux(mux)) => {
                let enum_name = mux_enum(cmu_ir, mux);
                muxes.insert((mux.register.to_string(), mux.field.to_string(), enum_name.clone()));
                mux_expr(p.name, cmu_ir, mux, &enum_name)
            }
        };
        writeln!(
            out,
            "impl crate::cmu::SealedCmuPeripheral for peripherals::{name} {{\n    \
             fn enable_bus_clock() {{\n        \
             crate::pac::CMU.{reg}_set().write(|w| w.set_{field}(true));\n    \
             }}\n    \
             fn frequency() -> crate::time::Hertz {{\n        \
             {frequency}\n    \
             }}\n}}\nimpl crate::cmu::CmuPeripheral for peripherals::{name} {{}}\n",
            name = p.name,
            reg = en.register,
            field = en.field,
        )
        .unwrap();
    }
    writeln!(out).unwrap();
    // `cmu.rs` includes the mux module, so it is `cmu::mux`.
    let mut mux_out = String::from("// Generated by embassy-silabs/build.rs. Do not edit.\n\n");
    write_clock_mux(&mut mux_out, &muxes);
    fs::write(out_dir.join("_cmu_mux.rs"), &mux_out).expect("write _cmu_mux.rs");

    writeln!(out, "embassy_hal_internal::peripherals_struct!(").unwrap();
    for s in &singletons {
        if s == time_driver_singleton {
            // The time driver owns it: keep the type, drop the field.
            continue;
        }
        writeln!(out, "    {s},").unwrap();
    }
    writeln!(out, ");\n").unwrap();

    // The generator already dedups `METADATA.interrupts`. This is a safeguard.
    let mut seen: BTreeSet<&str> = BTreeSet::new();
    let mut irq_names: Vec<&str> = Vec::new();
    for i in METADATA.interrupts {
        if seen.insert(i.name) {
            irq_names.push(i.name);
        }
    }
    writeln!(out, "embassy_hal_internal::interrupt_mod!(").unwrap();
    for name in &irq_names {
        writeln!(out, "    {name},").unwrap();
    }
    writeln!(out, ");\n").unwrap();

    if !time_driver_singleton.is_empty() {
        if !METADATA.interrupts.iter().any(|i| i.name == time_driver_singleton) {
            panic!("Tried to select {time_driver_singleton}, which is not available on this device");
        }
        writeln!(out).unwrap();
        writeln!(out, "#[cfg(feature = \"rt\")]").unwrap();
        writeln!(out, "#[interrupt]").unwrap();
        writeln!(out, "fn {time_driver_singleton}() {{").unwrap();
        writeln!(out, "    crate::time_driver::get_driver().on_interrupt();").unwrap();
        writeln!(out, "}}").unwrap();
    }

    fs::write(&out_path, &out).expect("write _generated.rs");

    // Chip cfgs from silabs-metapac `links` metadata: `silabs_series="2"`,
    // `silabs_series_2_config="6"` (MG26), and per peripheral `<kind>`, `<kind>_<version>` and its
    // prefixes (`timer_s2`, `timer_s2v0`). `rerun-if-changed=build.rs` turns off the default rerun
    // rules, so the metapac variables need their own rule, or the cfgs go stale.
    let dep = |key: &str| {
        println!("cargo:rerun-if-env-changed=DEP_SILABS_METAPAC_{key}");
        env::var(format!("DEP_SILABS_METAPAC_{key}"))
            .unwrap_or_else(|_| panic!("DEP_SILABS_METAPAC_{key} not set; silabs-metapac >= 0.6 is required"))
    };
    for spec in dep("CHECK_CFGS").split_ascii_whitespace() {
        println!("cargo:rustc-check-cfg={spec}");
    }
    for cfg in dep("CFGS").split_ascii_whitespace() {
        println!("cargo:rustc-cfg={cfg}");
    }

    println!("cargo:rerun-if-changed=build.rs");
}

/// `Clocks` fields that `cmu::init_clocks` fills in. A mux source that is
/// not in this list (an external pin, CLKIN0, a PLL) makes `frequency()`
/// panic when the mux selects it.
const CLOCKS: &[&str] = &[
    "hfxo",
    "hfrcodpll",
    "hfrcoem23",
    "fsrco",
    "lfxo",
    "lfrco",
    "ulfrco",
    "sysclk",
    "hclk",
    "pclk",
    "lspclk",
    "em01grpaclk",
    "em01grpbclk",
    "em01grpcclk",
    "em23grpaclk",
    "em4grpaclk",
];

/// Returns `clock` frequency divided by `div`, read from the frozen `Clocks` table.
fn clock_expr(peripheral: &str, clock: &str, div: u32) -> String {
    assert!(
        CLOCKS.contains(&clock),
        "{peripheral}: kernel clock `{clock}` is not a cmu::Clocks field"
    );
    let div = if div == 1 {
        String::new()
    } else {
        format!(" / {div}u32")
    };
    format!(
        "unwrap!(unsafe {{ crate::cmu::get_freqs() }}.{clock}, \
         \"peripheral '{{}}' uses the '{{}}' clock, which is not running\", {peripheral:?}, {clock:?}){div}"
    )
}

/// Maps a mux enum variant to `(Clocks field, divider)`.
///
/// Returns `None` for `Disabled` and for sources that `init_clocks` does not track.
fn mux_source(variant: &str) -> Option<(String, u32)> {
    let v = variant.to_ascii_lowercase();
    if v.starts_with("disable") {
        return None;
    }
    // `Hfxort` and `Hfrcodpllrt` are retimed copies of `Hfxo` and `Hfrcodpll`.
    let v = match v.strip_suffix("rt") {
        Some(base) if CLOCKS.contains(&base) => base.to_owned(),
        _ => v,
    };
    // `Hclkdiv1024` is HCLK / 1024.
    let (v, div) = match v.split_once("div") {
        Some((base, div)) if div.parse::<u32>().is_ok() => (base.to_owned(), div.parse().unwrap()),
        _ => (v, 1),
    };
    CLOCKS.contains(&v.as_str()).then_some((v, div))
}

/// Returns the enum name for a CMU select field.
fn mux_enum(ir: &IR, mux: &PeripheralCmuRegister) -> String {
    let block = ir
        .blocks
        .iter()
        .find(|b| b.name == "Cmu")
        .expect("CMU IR has no Cmu block");
    let item = block
        .items
        .iter()
        .find(|i| i.name == mux.register)
        .unwrap_or_else(|| panic!("CMU has no register {}", mux.register));
    let BlockItemInner::Register(reg) = &item.inner else {
        panic!("CMU {} is not a register", mux.register)
    };
    let fieldset = reg.fieldset.expect("mux register has no fieldset");
    let fs = ir.fieldsets.iter().find(|f| f.name == fieldset).unwrap();
    let field = fs.fields.iter().find(|f| f.name == mux.field).unwrap();
    field.enumm.expect("mux field has no enum").to_string()
}

/// Returns a `match` on the current value of a mux select field.
fn mux_expr(peripheral: &str, ir: &IR, mux: &PeripheralCmuRegister, enum_name: &str) -> String {
    let e = ir.enums.iter().find(|e| e.name == enum_name).unwrap();
    let mut arms = String::new();
    for v in e.variants {
        if let Some((clock, div)) = mux_source(v.name) {
            let expr = clock_expr(peripheral, &clock, div);
            writeln!(
                arms,
                "            crate::pac::cmu::vals::{enum_name}::{} => {{\n                {expr}\n            }}",
                v.name
            )
            .unwrap();
        }
    }
    format!(
        "match crate::pac::CMU.{reg}().read().{field}() {{\n\
         {arms}            \
         #[allow(unreachable_patterns)]\n            \
         _ => panic!(\"peripheral '{{}}' uses a clock source that embassy-silabs does not track\", {peripheral:?}),\n        \
         }}",
        reg = mux.register,
        field = mux.field,
    )
}

/// Returns the `ClockMux` field name for a select field: `eusart0clkctrl.clksel` becomes `eusart0`.
fn mux_field_name(register: &str, field: &str) -> String {
    let name = if field == "clksel" {
        register.strip_suffix("clkctrl")
    } else {
        field.strip_suffix("clksel")
    };
    name.unwrap_or_else(|| panic!("cannot name mux {register}.{field}"))
        .to_owned()
}

/// `cmu::mux::ClockMux`, like embassy-stm32's `rcc::mux::ClockMux`: one
/// field per peripheral clock select. `None` keeps the current value.
fn write_clock_mux(out: &mut String, muxes: &BTreeSet<(String, String, String)>) {
    let enums: BTreeSet<&str> = muxes.iter().map(|(_, _, e)| e.as_str()).collect();
    writeln!(out, "pub mod mux {{").unwrap();
    for e in &enums {
        writeln!(out, "    pub use crate::pac::cmu::vals::{e};").unwrap();
    }
    writeln!(
        out,
        "\n    /// Clock select of each peripheral that has one. `None` keeps the\n    \
         /// current value, which is the reset value after a reset.\n    \
         #[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]\n    \
         #[cfg_attr(feature = \"defmt\", derive(defmt::Format))]\n    \
         #[non_exhaustive]\n    \
         pub struct ClockMux {{"
    )
    .unwrap();
    for (reg, field, e) in muxes {
        writeln!(out, "        pub {}: Option<{e}>,", mux_field_name(reg, field)).unwrap();
    }
    writeln!(
        out,
        "    }}\n\n    impl ClockMux {{\n        pub const fn new() -> Self {{\n            Self {{"
    )
    .unwrap();
    for (reg, field, _) in muxes {
        writeln!(out, "                {}: None,", mux_field_name(reg, field)).unwrap();
    }
    writeln!(
        out,
        "            }}\n        }}\n\n        pub(crate) fn init(&self) {{"
    )
    .unwrap();
    for (reg, field, _) in muxes {
        writeln!(
            out,
            "            if let Some(v) = self.{} {{\n                \
             crate::pac::CMU.{reg}().modify(|w| w.set_{field}(v));\n            \
             }}",
            mux_field_name(reg, field)
        )
        .unwrap();
    }
    writeln!(out, "        }}\n    }}\n}}\n").unwrap();
}

/// Skip kinds that don't make sense as embassy peripheral singletons.
/// Conservative — only DEVINFO is dropped (read-only chip identity, not
/// a controllable peripheral). Security / mailbox / config peripherals
/// stay in so HALs can grow drivers for them without revisiting this list.
fn skip_peripheral_kind(kind: &str) -> bool {
    matches!(kind, "devinfo")
}

enum GetOneError {
    None,
    Multiple,
}

trait IteratorExt: Iterator {
    fn get_one(self) -> Result<Self::Item, GetOneError>;
}

impl<T: Iterator> IteratorExt for T {
    fn get_one(mut self) -> Result<Self::Item, GetOneError> {
        match self.next() {
            None => Err(GetOneError::None),
            Some(res) => match self.next() {
                Some(_) => Err(GetOneError::Multiple),
                None => Ok(res),
            },
        }
    }
}
