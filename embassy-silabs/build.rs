/// Writes `cmu::Clocks`, one `Option<Hertz>` field per [`clocks`] entry.
fn write_clocks(out: &mut String) {
    writeln!(
        out,
        "/// Frozen clock tree frequencies, set once by `init_clocks`.\n\
         ///\n\
         /// Field names match metapac `kernel_clock` names.\n\
         /// `None` means the clock is off or missing.\n\
         #[derive(Copy, Clone, Default, Eq, PartialEq, Debug)]\n\
         #[cfg_attr(feature = \"defmt\", derive(defmt::Format))]\n\
         #[non_exhaustive]\n\
         pub struct Clocks {{"
    )
    .unwrap();
    for clock in clocks() {
        writeln!(out, "    pub {clock}: Option<Hertz>,").unwrap();
    }
    writeln!(out, "}}\n").unwrap();
}

/// Writes `<name>_freq()`, which returns a group clock frequency.
///
/// The frequency comes from the current select value and the base clocks in `c`.
fn write_group_freq(out: &mut String, ir: &IR, name: &str, mux: &PeripheralCmuRegister, enum_name: &str) {
    let e = ir.enums.iter().find(|e| e.name == enum_name).unwrap();
    writeln!(
        out,
        "pub(crate) fn {name}_freq(c: &Clocks) -> Option<Hertz> {{\n    \
         #[allow(unreachable_patterns)]\n    \
         match crate::pac::CMU.{reg}().read().{field}() {{",
        reg = mux.register,
        field = mux.field,
    )
    .unwrap();
    for v in e.variants {
        let Some((clock, div)) = mux_source(v.name) else {
            continue;
        };
        let div = if div == 1 {
            String::new()
        } else {
            format!(".map(|f| f / {div}u32)")
        };
        writeln!(
            out,
            "        crate::pac::cmu::vals::{enum_name}::{} => c.{clock}{div},",
            v.name
        )
        .unwrap();
    }
    writeln!(out, "        _ => None,\n    }}\n}}\n").unwrap();
}

/// Writes `fill_group_freqs()`, which fills each group clock in `c`.
///
/// Series 0 has no group clocks, so the function is empty there.
fn write_fill_group_freqs(out: &mut String, fields: &[(String, String, String, String)]) {
    let groups: Vec<_> = fields
        .iter()
        .filter(|(name, ..)| clocks().contains(&name.as_str()))
        .collect();
    let param = if groups.is_empty() { "_c" } else { "c" };
    writeln!(out, "pub(crate) fn fill_group_freqs({param}: &mut Clocks) {{").unwrap();
    for (name, ..) in groups {
        writeln!(out, "    c.{name} = {name}_freq(c);").unwrap();
    }
    writeln!(out, "}}\n").unwrap();
}

/// Writes `cmu::mux::ClockMux`, with one field per group and peripheral clock select.
///
/// `muxes` holds `(field, register, select field, enum)`. `init` writes only the `Some` fields.
fn write_clock_mux(out: &mut String, muxes: &[(String, String, String, String)]) {
    let enums: BTreeSet<&str> = muxes.iter().map(|(_, _, _, e)| e.as_str()).collect();
    writeln!(out, "pub mod mux {{").unwrap();
    for e in &enums {
        writeln!(out, "    pub use crate::pac::cmu::vals::{e};").unwrap();
    }
    writeln!(
        out,
        "\n    /// Group and peripheral clock selects. `init` writes only the `Some` fields.\n    \
         #[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]\n    \
         #[cfg_attr(feature = \"defmt\", derive(defmt::Format))]\n    \
         #[non_exhaustive]\n    \
         pub struct ClockMux {{"
    )
    .unwrap();
    for (name, _, _, e) in muxes {
        writeln!(out, "        pub {name}: Option<{e}>,").unwrap();
    }
    writeln!(
        out,
        "    }}\n\n    impl ClockMux {{\n        pub const fn new() -> Self {{\n            Self {{"
    )
    .unwrap();
    for (name, ..) in muxes {
        writeln!(out, "                {name}: None,").unwrap();
    }
    writeln!(
        out,
        "            }}\n        }}\n\n        pub(crate) fn init(&self) {{"
    )
    .unwrap();
    for (name, reg, field, _) in muxes {
        writeln!(
            out,
            "            if let Some(v) = self.{name} {{\n                \
             crate::pac::CMU.{reg}().modify(|w| w.set_{field}(v));\n            \
             }}"
        )
        .unwrap();
    }
    writeln!(out, "        }}\n    }}\n}}\n").unwrap();
}

/// Rows for the `foreach_*!` table macros.
struct Tables {
    /// `(kind, NAME)` per singleton peripheral.
    peripherals: Vec<Vec<String>>,
    /// `(NAME, kind, SIGNAL, IRQ)` per interrupt that belongs to a peripheral.
    interrupts: Vec<Vec<String>>,
    /// `(PIN, port * 16 + pin)` per GPIO pin.
    pins: Vec<Vec<String>>,
}

impl Tables {
    fn new(singletons: &[String], pins: &[(String, u8)]) -> Self {
        let peris: Vec<_> = METADATA
            .peripherals
            .iter()
            .filter(|p| singletons.iter().any(|s| s == p.name))
            .collect();
        let peripherals = peris
            .iter()
            .map(|p| vec![p.kind.to_string(), p.name.to_string()])
            .collect();

        let interrupts = peris
            .iter()
            .flat_map(|p| {
                p.interrupts.iter().map(|i| {
                    vec![
                        p.name.to_string(),
                        p.kind.to_string(),
                        i.signal.to_string(),
                        i.interrupt.to_string(),
                    ]
                })
            })
            .collect();

        let pins = pins.iter().map(|(name, n)| vec![name.clone(), n.to_string()]).collect();
        Self {
            peripherals,
            interrupts,
            pins,
        }
    }
}

/// Writes a table macro.
///
/// The caller's arms become an inner macro that runs once per row. When a row matches no arm, the
/// macro expands to nothing.
fn make_table(out: &mut String, name: &str, data: &[Vec<String>]) {
    write!(
        out,
        "#[allow(unused)]
macro_rules! {} {{
    ($($pat:tt => $code:tt;)*) => {{
        macro_rules! __{}_inner {{
            $(($pat) => $code;)*
            ($_:tt) => {{}}
        }}
",
        name, name
    )
    .unwrap();

    for row in data {
        writeln!(out, "        __{}_inner!(({}));", name, row.join(",")).unwrap();
    }

    writeln!(
        out,
        "    }};
}}"
    )
    .unwrap();
}

/// Writes `impl_eusart!` per EUSART.
///
/// `macro_rules!` cannot join identifiers, so the interrupt and GPIO route names are spelled out.
///
/// Also `pin_trait_impl!` for `TxPin` and `RxPin`, one for each pin of the
/// `Dbus` entry of the `TX` and `RX` signals in `Peripheral.pins`. The entry
/// must name the route register and the `routeen` enable field that
/// `impl_eusart!` writes.
fn write_eusart_impls(out: &mut String) {
    let gpio_items: Vec<&str> = METADATA
        .peripherals
        .iter()
        .find(|p| p.name == "GPIO")
        .map(|p| {
            p.ir.blocks
                .iter()
                .flat_map(|b| b.items.iter().map(|i| i.name))
                .collect()
        })
        .unwrap_or_default();
    for p in METADATA.peripherals.iter().filter(|p| p.kind == "eusart") {
        let route = |suffix: &str| {
            let name = format!("{}_{suffix}", p.name.to_ascii_lowercase());
            assert!(gpio_items.contains(&name.as_str()), "GPIO has no {name} register");
            name
        };
        writeln!(
            out,
            "crate::eusart::impl_eusart!({}, {}, {}, {}, {}, {});",
            p.name,
            irq(p, "RX"),
            irq(p, "TX"),
            route("txroute"),
            route("rxroute"),
            route("routeen"),
        )
        .unwrap();
        let routeen = route("routeen");
        for (signal, trait_name, suffix, field) in
            [("TX", "TxPin", "txroute", "txpen"), ("RX", "RxPin", "rxroute", "rxpen")]
        {
            let register = route(suffix);
            let mut n = 0;
            for e in p.pins.iter().filter(|e| e.signal == signal) {
                let PinRoute::Dbus { register: r, enable } = &e.route else {
                    panic!("{} {signal}: not a DBUS route: {:?}", p.name, e.route);
                };
                assert_eq!(*r, register, "{} {signal}: route register", p.name);
                // `impl_eusart!` sets `GPIO.<routeen>.txpen` and `.rxpen`.
                check_enable(p.name, signal, enable, &routeen, field);
                for pin in e.pins {
                    writeln!(out, "pin_trait_impl!(crate::eusart::{trait_name}, {}, {pin});", p.name).unwrap();
                    n += 1;
                }
            }
            assert!(n > 0, "{} has no {signal} pins in the metadata", p.name);
        }
    }
    writeln!(out).unwrap();
}

/// Writes GPIO external interrupt data for `gpio::exti`.
///
/// The data is the line count, the `GPIO_EVEN` and `GPIO_ODD` IRQs, and their handlers with the
/// `rt` feature. The line count is the width of `EXTIRISE.EXTIRISE`: 16 on Series 0 and MG26, and
/// 12 on MG22, MG24 and FG25.
fn write_gpio_exti(out: &mut String) {
    let gpio = METADATA
        .peripherals
        .iter()
        .find(|p| p.name == "GPIO")
        .expect("chip has no GPIO");
    let lines = field_bit_size(gpio.ir, "extirise", "extirise")
        .unwrap_or_else(|| panic!("GPIO IR has no EXTIRISE.EXTIRISE field"));
    assert_eq!(
        field_bit_size(gpio.ir, "extifall", "extifall"),
        Some(lines),
        "GPIO EXTIFALL and EXTIRISE have different widths"
    );
    assert!(lines <= 16, "GPIO has {lines} EXTI lines, more than 16");
    let (even, odd) = (irq(gpio, "EVEN"), irq(gpio, "ODD"));
    writeln!(
        out,
        "pub(crate) mod _generated_exti {{\n    \
         /// Number of GPIO external interrupt lines.\n    \
         pub(crate) const LINES: usize = {lines};\n    \
         pub(crate) const EVEN_IRQ: crate::interrupt::Interrupt = crate::interrupt::Interrupt::{even};\n    \
         pub(crate) const ODD_IRQ: crate::interrupt::Interrupt = crate::interrupt::Interrupt::{odd};\n\
         }}\n\n\
         #[cfg(feature = \"rt\")]\n#[interrupt]\nfn {even}() {{\n    crate::gpio::exti::on_interrupt(0x5555);\n}}\n\n\
         #[cfg(feature = \"rt\")]\n#[interrupt]\nfn {odd}() {{\n    crate::gpio::exti::on_interrupt(0xAAAA);\n}}\n"
    )
    .unwrap();
}

/// Returns the width of `register.field` in the first block of `ir` that has the register.
fn field_bit_size(ir: &IR, register: &str, field: &str) -> Option<u32> {
    ir.blocks.iter().find_map(|b| {
        let item = b.items.iter().find(|i| i.name == register)?;
        let BlockItemInner::Register(reg) = &item.inner else {
            return None;
        };
        let fs = ir.fieldsets.iter().find(|f| Some(f.name) == reg.fieldset)?;
        fs.fields.iter().find(|f| f.name == field).map(|f| f.bit_size)
    })
}

/// Checks that a route's enable field is the one that the driver writes.
fn check_enable(peripheral: &str, signal: &str, enable: &Option<PinRouteEnable>, register: &str, field: &str) {
    match enable {
        Some(e) if e.register == register && e.field == field => {}
        other => {
            panic!("{peripheral} {signal}: the metadata enable is {other:?}, but the driver sets `{register}.{field}`")
        }
    }
}

/// Writes `impl_usart!` for each Series 0 USART and UART.
///
/// Both have metadata kind `usart`, because UART0 and UART1 are USART blocks in asynchronous mode.
///
/// Also writes `pin_trait_impl!` for `TxPin` and `RxPin`. A pin can be at several locations for a
/// signal (USART0 CLK PB13 is at 4 and 5), so each pin gets one impl with all its `Location`
/// numbers. Each entry must enable the `route` field that `impl_usart!` writes.
fn write_usart_s0_impls(out: &mut String) {
    for p in METADATA.peripherals.iter().filter(|p| p.kind == "usart") {
        writeln!(
            out,
            "crate::usart::impl_usart!({}, {}, {});",
            p.name,
            irq(p, "RX"),
            irq(p, "TX"),
        )
        .unwrap();
        for (signal, trait_name, field) in [("TX", "TxPin", "txpen"), ("RX", "RxPin", "rxpen")] {
            let locations = locations_by_pin(p, signal);
            for e in p.pins.iter().filter(|e| e.signal == signal) {
                let PinRoute::Location { enable, .. } = &e.route else {
                    panic!("{} {signal}: not a Location route: {:?}", p.name, e.route);
                };
                check_enable(p.name, signal, enable, "route", field);
            }
            // EFM32GG900 (die parts) has no pin data. The instance stays usable from the PAC, but
            // `Uart::new_blocking` accepts no pin.
            if locations.is_empty() {
                println!(
                    "cargo:warning={} has no {signal} pins in the metadata, so no {trait_name} impls",
                    p.name
                );
            }
            for (pin, locs) in locations {
                let locs: Vec<String> = locs.iter().map(u8::to_string).collect();
                writeln!(
                    out,
                    "pin_trait_impl!(crate::usart::{trait_name}, {}, {pin}, [{}]);",
                    p.name,
                    locs.join(", ")
                )
                .unwrap();
            }
        }
    }
    check_usart1_af();
}

/// Returns the `Location` numbers for each pin of a signal.
///
/// The pins are in `METADATA.pins` order: by port, then by pin number.
fn locations_by_pin(p: &Peripheral, signal: &str) -> Vec<(&'static str, Vec<u8>)> {
    let mut out: Vec<(&'static str, Vec<u8>)> = Vec::new();
    for bonded in METADATA.pins {
        let mut locs: Vec<u8> = p
            .pins
            .iter()
            .filter(|e| e.signal == signal && e.pins.contains(&bonded.name))
            .filter_map(|e| match e.route {
                PinRoute::Location { location, .. } => Some(location),
                _ => None,
            })
            .collect();
        locs.sort_unstable();
        if !locs.is_empty() {
            out.push((bonded.name, locs));
        }
    }
    out
}

/// EFM32GG USART1 locations as `(signal, [(location, pin)])`.
///
/// The values come from EFM32GG datasheet table 5.2 (Alternate Functionality Overview).
const EFM32GG_USART1_AF: &[(&str, &[(u8, &str)])] = &[
    ("TX", &[(0, "PC0"), (1, "PD0"), (2, "PD7")]),
    ("RX", &[(0, "PC1"), (1, "PD1"), (2, "PD6")]),
];

/// Checks EFM32GG metadata at build time.
///
/// The USART1 locations must equal the datasheet table, filtered by the bonded pins.
fn check_usart1_af() {
    if !METADATA.name.starts_with("EFM32GG") {
        return;
    }
    let Some(p) = METADATA.peripherals.iter().find(|p| p.name == "USART1") else {
        return;
    };
    // EFM32GG900 (die parts) has no pin data, so there is nothing to check.
    if p.pins.is_empty() {
        return;
    }
    for &(signal, table) in EFM32GG_USART1_AF {
        let expected: Vec<(&str, Vec<u8>)> = METADATA
            .pins
            .iter()
            .filter_map(|b| {
                let locs: Vec<u8> = table
                    .iter()
                    .filter(|(_, pin)| *pin == b.name)
                    .map(|(n, _)| *n)
                    .collect();
                (!locs.is_empty()).then_some((b.name, locs))
            })
            .collect();
        assert_eq!(
            locations_by_pin(p, signal),
            expected,
            "{}: USART1 {signal} locations differ from the EFM32GG AF headers",
            METADATA.name
        );
    }
}

/// Writes `timer::Instance` and the counter width trait per TIMER singleton.
fn write_timer_impls(out: &mut String, singletons: &[String]) {
    for p in METADATA
        .peripherals
        .iter()
        .filter(|p| p.kind == "timer" && singletons.iter().any(|s| s == p.name))
    {
        let (level, f, block) = match p.block {
            "Timer32" => ("Instance32bit", "regs_32bit", "Timer32"),
            "Timer" => ("Instance16bit", "regs_16bit", "Timer"),
            b => panic!("{}: unknown TIMER block {b}", p.name),
        };
        writeln!(
            out,
            "impl crate::timer::SealedInstance for peripherals::{name} {{}}\n\
             impl crate::timer::Instance for peripherals::{name} {{\n    \
             type Interrupt = crate::interrupt::typelevel::{irq};\n}}\n\
             impl crate::timer::{level} for peripherals::{name} {{\n    \
             fn {f}() -> crate::pac::timer::{block} {{\n        \
             crate::pac::{name}\n    \
             }}\n}}\n",
            name = p.name,
            irq = irq(p, "GLOBAL"),
        )
        .unwrap();
    }
}

/// Returns the IRQ for `signal` (`GLOBAL`, `RX`) on `p`, from `Peripheral.interrupts`.
fn irq(p: &Peripheral, signal: &str) -> &'static str {
    p.interrupts
        .iter()
        .find(|i| i.signal == signal)
        .map(|i| i.interrupt)
        .unwrap_or_else(|| panic!("{} has no {signal} interrupt", p.name))
}

/// Returns `true` for peripheral kinds that get no singleton.
///
/// These are DEVINFO and the Series 0 ROMTABLE, which only hold read-only chip identity. Other
/// kinds keep a singleton for future drivers.
fn skip_peripheral_kind(kind: &str) -> bool {
    matches!(kind, "devinfo" | "romtable")
}

enum GetOneError {
    None,
    Multiple,
}

trait IteratorExt: Iterator {
    fn get_one(self) -> Result<Self::Item, GetOneError>;
}

impl<T: Iterator> IteratorExt for T {
    fn get_one(mut self) -> Result<Self::Item, GetOneError> {
        match self.next() {
            None => Err(GetOneError::None),
            Some(res) => match self.next() {
                Some(_) => Err(GetOneError::Multiple),
                None => Ok(res),
            },
        }
    }
}
