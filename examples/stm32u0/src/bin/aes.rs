//! AES known-answer tests for the `aes_v2` hardware block.
//!
//! Runs every supported cipher mode against published test vectors and prints a
//! pass/fail tally over RTT. Vectors come from NIST SP 800-38A (ECB, CBC, CTR),
//! SP 800-38D (GCM, GMAC), and an ST HAL CCM vector.
//!
//! On `aes_v2` parts the engine has no dedicated interrupt vector, so the driver
//! is constructed with [`Aes::new_blocking`] and takes no interrupt binding.

#![no_std]
#![no_main]

use defmt::*;
use defmt_rtt as _;
use embassy_stm32::aes::{Aes, AesCbc, AesCcm, AesCtr, AesEcb, AesGcm, AesGmac, Direction};
use panic_probe as _;

/// Running count of passed and failed checks.
struct Tally {
    pass: u32,
    fail: u32,
}

impl Tally {
    fn check(&mut self, name: &str, got: &[u8], want: &[u8]) {
        if got == want {
            self.pass += 1;
            info!("  PASS {}", name);
        } else {
            self.fail += 1;
            error!("  FAIL {}", name);
            error!("    got  {:02x}", got);
            error!("    want {:02x}", want);
        }
    }
}

